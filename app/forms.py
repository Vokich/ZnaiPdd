  def check_answers(self, passing_score=18):
    results = {}
    score = 0
    total = len(self.questions_data)
    for q in self.questions_data:
      field_name = f'question_{q["id"]}'
      user_answer = self.cleaned_data.get(field_name)
      if user_answer:
        user_answer_int = int(user_answer)
        is_correct = (user_answer_int == q['correct'])
        results[q['id']] = {
          'question': q['text'],
          'user_answer': user_answer_int,
          'correct_answer': q['correct'],
          'is_correct': is_correct
        }
        if is_correct:
          score += 1
    passed = (score >= passing_score)
    return {
      'score': score,
      'total': total,
      'passing_score': passing_score,
      'passed': passed,
      'results': results
    }

