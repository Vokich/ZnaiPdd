from django import forms
from django.contrib.auth.models import User
from django.core.exceptions import ValidationError
from .models import Profile, TeacherLessonReport


class UserRegistrationForm(forms.ModelForm):
    username = forms.CharField(
        label='Логин',
        max_length=150,
        widget=forms.TextInput(attrs={'class': 'form-control'})
    )
    password = forms.CharField(
        label='Пароль',
        widget=forms.PasswordInput(attrs={'class': 'form-control'})
    )
    surname1 = forms.CharField(
        label='Фамилия',
        max_length=50,
        widget=forms.TextInput(attrs={'class': 'form-control'})
    )
    name = forms.CharField(
        label='Имя',
        max_length=50,
        widget=forms.TextInput(attrs={'class': 'form-control'})
    )
    surname2 = forms.CharField(
        label='Отчество',
        max_length=50,
        required=False,
        widget=forms.TextInput(attrs={'class': 'form-control'})
    )
    email = forms.EmailField(
        label='Почта',
        required=True,
        widget=forms.EmailInput(attrs={'class': 'form-control'})
    )
    school = forms.CharField(
        label='Учебное заведение',
        max_length=100,
        widget=forms.TextInput(attrs={'class': 'form-control'})
    )
    birth_date = forms.DateField(
        label='Дата рождения',
        widget=forms.DateInput(attrs={'type': 'date', 'class': 'form-control'}),
    )
    region = forms.CharField(
        label='Муниципалитет',
        max_length=400,
        widget=forms.TextInput(attrs={'class': 'form-control'})
    )
    role = forms.ChoiceField(
        label='Роль',
        choices=Profile.Role.choices,
        widget=forms.Select(attrs={'class': 'form-control', 'id': 'id_role'})
    )
    position = forms.CharField(
        label='Должность',
        max_length=100,
        required=False,
        widget=forms.TextInput(attrs={'class': 'form-control', 'id': 'id_position'})
    )

    class Meta:
        model = User
        fields = ['username', 'email', 'password']

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

    def clean_username(self):
        username = self.cleaned_data.get('username')
        if username and User.objects.filter(username=username).exists():
            raise ValidationError("Пользователь с таким логином уже существует")
        return username

    def clean_email(self):
        email = self.cleaned_data.get('email')
        if email and User.objects.filter(email=email).exists():
            raise ValidationError("Пользователь с таким email уже существует")
        return email

    def clean_birth_date(self):
        birth_date = self.cleaned_data.get('birth_date')
        from datetime import date
        if birth_date and birth_date > date.today():
            raise ValidationError("Дата рождения не может быть в будущем")
        return birth_date

    def clean(self):
        cleaned_data = super().clean()
        role = cleaned_data.get('role')
        position = cleaned_data.get('position')
        if role == 'teacher' and not position:
            self.add_error('position', 'Поле "Должность" обязательно для педагога')

        return cleaned_data

    def save(self, commit=True):
        user = User(
            username=self.cleaned_data['username'],
            email=self.cleaned_data['email']
        )
        user.set_password(self.cleaned_data['password'])

        if commit:
            user.save()
            Profile.objects.create(
                user=user,
                role=self.cleaned_data['role'],
                surname1=self.cleaned_data['surname1'],
                name=self.cleaned_data['name'],
                surname2=self.cleaned_data['surname2'],
                school=self.cleaned_data['school'],
                birth_date=self.cleaned_data['birth_date'],
                region=self.cleaned_data['region'],
                position=self.cleaned_data.get('position', '')
            )
        return user


